import { spawn } from "node:child_process";
import { mkdir, readdir, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const videosDirectory = path.join(projectRoot, "public", "images", "students");
const manifestPath = path.join(projectRoot, "src", "data", "generated", "student-video-posters.ts");
const cachePath = path.join(projectRoot, "scripts", ".student-thumbnail-cache.json");
const seekSeconds = "1";

async function listVideos(directory) {
  try {
    const entries = await readdir(directory, { withFileTypes: true });
    const nested = await Promise.all(
      entries.map(async (entry) => {
        const entryPath = path.join(directory, entry.name);
        if (entry.isDirectory()) return listVideos(entryPath);
        return entry.isFile() && path.extname(entry.name).toLowerCase() === ".mp4"
          ? [entryPath]
          : [];
      }),
    );

    return nested.flat();
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
      return [];
    }
    throw error;
  }
}

async function readCache() {
  try {
    return JSON.parse(await readFile(cachePath, "utf8"));
  } catch {
    return {};
  }
}

function runFfmpeg(args) {
  return new Promise((resolve) => {
    const process = spawn("ffmpeg", args, { stdio: "ignore" });
    process.on("error", () => resolve(false));
    process.on("close", (code) => resolve(code === 0));
  });
}

async function isFfmpegAvailable() {
  return runFfmpeg(["-version"]);
}

async function createPoster(videoPath, posterPath) {
  const temporaryPath = `${posterPath}.tmp.webp`;
  const baseArguments = [
    "-y",
    "-ss",
    seekSeconds,
    "-i",
    videoPath,
    "-frames:v",
    "1",
    "-vf",
    "scale=min(720\\,iw):-2",
    "-c:v",
    "libwebp",
    "-q:v",
    "82",
  ];

  await rm(temporaryPath, { force: true });
  let succeeded = await runFfmpeg([...baseArguments, temporaryPath]);

  // A seek beyond a short video's duration can fail, so retry from its first frame.
  if (!succeeded) {
    await rm(temporaryPath, { force: true });
    succeeded = await runFfmpeg([
      "-y",
      "-i",
      videoPath,
      "-frames:v",
      "1",
      "-vf",
      "scale=min(720\\,iw):-2",
      "-c:v",
      "libwebp",
      "-q:v",
      "82",
      temporaryPath,
    ]);
  }

  if (succeeded) await rename(temporaryPath, posterPath);
  else await rm(temporaryPath, { force: true });

  return succeeded;
}

function createManifest(posters) {
  const entries = Object.entries(posters)
    .sort(([first], [second]) => first.localeCompare(second))
    .map(([video, poster]) => `  ${JSON.stringify(video)}: ${JSON.stringify(poster)},`)
    .join("\n");

  return `// This file is generated by scripts/generate-student-thumbnails.mjs.\n// Do not edit manually.\n\nconst studentVideoPosters: Record<string, string> = {\n${entries}\n};\n\nexport function getStudentVideoPoster(video: string) {\n  return studentVideoPosters[video];\n}\n`;
}

async function main() {
  const videos = await listVideos(videosDirectory);
  const cache = await readCache();
  const ffmpegAvailable = await isFfmpegAvailable();
  const posters = {};

  if (!ffmpegAvailable && videos.length > 0) {
    console.warn(
      "[student-thumbnails] FFmpeg was not found. Skipping poster generation; existing posters will still be used.",
    );
  }

  for (const videoPath of videos) {
    const relativeVideoPath = path.relative(videosDirectory, videoPath);
    const posterPath = path.join(
      path.dirname(videoPath),
      `${path.basename(videoPath, path.extname(videoPath))}.webp`,
    );
    const publicVideoPath = `/images/students/${relativeVideoPath.split(path.sep).join("/")}`;
    const publicPosterPath = publicVideoPath.replace(/\.mp4$/i, ".webp");
    const videoStats = await stat(videoPath);
    const fingerprint = `${videoStats.mtimeMs}:${videoStats.size}`;

    try {
      const posterStats = await stat(posterPath);
      if (posterStats.mtimeMs >= videoStats.mtimeMs) {
        posters[publicVideoPath] = publicPosterPath;
        delete cache[videoPath];
        continue;
      }
    } catch {
      // Generate a poster when one does not yet exist.
    }

    if (!ffmpegAvailable || cache[videoPath]?.fingerprint === fingerprint) continue;

    const created = await createPoster(videoPath, posterPath);
    if (created) {
      posters[publicVideoPath] = publicPosterPath;
      delete cache[videoPath];
      console.log(`[student-thumbnails] Generated ${publicPosterPath}`);
    } else {
      cache[videoPath] = { fingerprint };
      console.warn(`[student-thumbnails] Could not create a poster for ${publicVideoPath}.`);
    }
  }

  await mkdir(path.dirname(manifestPath), { recursive: true });
  await writeFile(manifestPath, createManifest(posters));
  await writeFile(cachePath, `${JSON.stringify(cache, null, 2)}\n`);
}

main().catch((error) => {
  console.error("[student-thumbnails] Unexpected error:", error);
  process.exitCode = 1;
});
